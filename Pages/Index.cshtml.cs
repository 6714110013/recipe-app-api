using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.RazorPages;
using Microsoft.AspNetCore.Mvc.Rendering;
using RecipeApp.Models;

namespace RecipeApp.Pages
{
    [Authorize]
    public class IndexModel : PageModel
    {
        private readonly RecipeService _service;

        public IEnumerable<RecipeSummaryViewModel> Recipes { get; private set; } = new List<RecipeSummaryViewModel>();

        // ????????????????????????????? Query String
        [BindProperty(SupportsGet = true)]
        public string? SearchCategory { get; set; }

        // ???????????????????????????? Dropdown
        public SelectList Categories { get; set; } = default!;

        public IndexModel(RecipeService service)
        {
            _service = service;
        }

        public async Task OnGet()
        {
            // ????????????????????????????? Service
            var allRecipes = await _service.GetRecipes();

            // ??????????????????????????????????????? ???????????? Dropdown
            var categoryList = allRecipes
                .Where(r => !string.IsNullOrEmpty(r.Category))
                .Select(r => r.Category)
                .Distinct()
                .OrderBy(c => c)
                .ToList();

            Categories = new SelectList(categoryList);

            // ??????????????????????????????????? (???????????????????????????)
            if (!string.IsNullOrEmpty(SearchCategory))
            {
                Recipes = allRecipes.Where(r => r.Category == SearchCategory);
            }
            else
            {
                Recipes = allRecipes;
            }
        }
    }
}